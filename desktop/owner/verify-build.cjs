'use strict';
const fs=require('node:fs');
const path=require('node:path');
const assert=require('node:assert/strict');
const crypto=require('node:crypto');
const asar=require('@electron/asar');
const resedit=require('resedit');
const folder=path.join(__dirname,'dist');
const archive=path.join(folder,'win-unpacked','resources','app.asar');
for(const file of ['main.cjs','preload.cjs','ui.js','index.html','license-core.cjs'])assert.deepEqual(asar.extractFile(archive,file),fs.readFileSync(path.join(__dirname,file)));
assert.deepEqual(fs.readFileSync(path.join(__dirname,'license-core.cjs')),fs.readFileSync(path.join(__dirname,'..','licensing','core.cjs')));
const files=asar.listPackage(archive);assert.equal(files.some(file=>/\.pem$|\.kplicense$|issued-licenses/.test(file)),false);
const bytes=fs.readFileSync(archive);assert.equal(/-----BEGIN (?:ENCRYPTED )?PRIVATE KEY-----\r?\n[A-Za-z0-9+/=\r\n]{32,}/.test(bytes.toString('utf8')),false);
const native=fs.readFileSync(path.join(folder,'win-unpacked','KP Master Activation.exe'));
assert.equal(native.readUInt16LE(native.readUInt32LE(0x3c)+4),0x8664);
const resources=resedit.NtExecutableResource.from(resedit.NtExecutable.from(native));
const version=resedit.Resource.VersionInfo.fromEntries(resources.entries)[0];
assert.equal(version.getStringValues(version.getAllLanguagesForStringValues()[0]).ProductName,'KP Master Activation');
const executable='KP-Master-Owner-Activation-1.0.0-x64.exe';
const exe=fs.readFileSync(path.join(folder,executable));assert.equal(exe.toString('ascii',0,2),'MZ');
const sha=crypto.createHash('sha256').update(exe).digest('hex');
fs.writeFileSync(path.join(folder,'SHA256SUMS.txt'),sha+'  '+executable+'\n');
console.log(JSON.stringify({executable,bytes:exe.length,sha256:sha,ownerAppParity:true,privateKeysPackaged:false},null,2));
