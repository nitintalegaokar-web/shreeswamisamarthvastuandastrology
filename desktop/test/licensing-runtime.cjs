'use strict';
const {_electron}=require('playwright');
const assert=require('node:assert/strict');
const fs=require('node:fs/promises');
const path=require('node:path');
const os=require('node:os');
const crypto=require('node:crypto');
const {execFileSync}=require('node:child_process');
const core=require('../licensing/core.cjs');
const {getSystemId}=require('../licensing/system-id.cjs');
(async()=>{
  const temporary=await fs.mkdtemp(path.join(os.tmpdir(),'kp-license-test-'));
  const ownerPrivate=path.join(temporary,'owner.private-key.pem'),ownerPublic=path.join(temporary,'owner-public.pem'),licenseFile=path.join(temporary,'client.kplicense');
  const password='Test-only-owner-password-123';
  const systemId=await getSystemId();
  const root=path.resolve(__dirname,'..');
  execFileSync(process.execPath,[path.join(root,'owner','prepare.cjs')]);
  const options=dir=>({executablePath:require('electron'),args:[dir,...(process.platform==='linux'?['--no-sandbox','--disable-gpu']:[]),'--user-data-dir='+path.join(temporary,path.basename(dir)+'-profile')],env:{...process.env,XDG_CONFIG_HOME:path.join(temporary,path.basename(dir)+'-config')},timeout:60000});
  let owner,client;
  try{
    owner=await _electron.launch(options(path.join(root,'owner')));
    const page=await owner.firstWindow();await page.waitForFunction('typeof KPOwner!=="undefined"');
    assert.equal(await page.evaluate('typeof require'),'undefined');assert.equal((await page.evaluate('KPOwner.status()')).unlocked,false);
    await owner.evaluate(({dialog},files)=>{
      dialog.showSaveDialog=async(_window,settings)=>({canceled:false,filePath:settings.title.includes('private key')?files.private:settings.title.includes('public key')?files.public:files.license});
      dialog.showOpenDialog=async()=>({canceled:false,filePaths:[files.private]});
    },{private:ownerPrivate,public:ownerPublic,license:licenseFile});
    await page.locator('#password').fill(password);await page.locator('#confirm').fill(password);await page.locator('#create').click();
    await page.waitForFunction('!document.getElementById("export-public").disabled');
    const encrypted=await fs.readFile(ownerPrivate,'utf8');assert.match(encrypted,/BEGIN ENCRYPTED PRIVATE KEY/);assert.doesNotMatch(encrypted,/BEGIN PRIVATE KEY/);
    assert.equal(await page.locator('#password').inputValue(),'');
    await page.locator('#export-public').click();await page.waitForFunction('document.getElementById("status").textContent.includes("Public key exported")');
    const publicPem=await fs.readFile(ownerPublic,'utf8');assert.match(publicPem,/BEGIN PUBLIC KEY/);assert.doesNotMatch(publicPem,/PRIVATE/);
    await page.locator('#client').fill('Runtime client');await page.locator('#system').fill(systemId);await page.locator('#issue').click();
    await page.waitForFunction('document.getElementById("status").textContent.startsWith("Saved ")');
    const license=JSON.parse(await fs.readFile(licenseFile,'utf8'));assert.equal(core.verify(license,publicPem,systemId).clientName,'Runtime client');
    await page.locator('#lock').click();await page.waitForFunction('document.getElementById("issue").disabled');
    await assert.rejects(()=>page.evaluate('KPOwner.issue({})'),/key first/);
    await page.locator('#password').fill('Incorrect-password-123');await page.locator('#open').click();await page.waitForFunction('document.getElementById("status").textContent.includes("incorrect")');
    assert.equal((await page.evaluate('KPOwner.status()')).unlocked,false);
    await page.locator('#password').fill(password);await page.locator('#open').click();await page.waitForFunction('!document.getElementById("issue").disabled');
    assert.equal((await page.evaluate('KPOwner.history()')).length,1);
    await owner.close();owner=null;
    console.log('PASS owner: local encrypted key, public-only export, signed issuance, wrong-password rejection, key lock and history.');
    execFileSync(process.execPath,[path.join(root,'prepare.cjs')],{env:{...process.env,KP_LICENSE_PUBLIC_KEY_FILE:ownerPublic}});
    client=await _electron.launch(options(root));const locked=await client.firstWindow();
    await locked.waitForFunction('document.getElementById("system-id")?.value.startsWith("KP1-")');
    assert.equal(await locked.locator('#system-id').inputValue(),systemId);assert.equal(await locked.evaluate('typeof KPAutomaticCalculations'),'undefined');
    await assert.rejects(()=>locked.evaluate('KPDesktopFiles.save("{}","bypass.lkp")'),/Untrusted/);
    const forgedFile=path.join(temporary,'wrong-computer.kplicense');
    const wrongId=core.systemId({machineGuid:'aa112233445566778899aabbccddeeff'});
    const privateKey=crypto.createPrivateKey({key:encrypted,passphrase:password});
    await fs.writeFile(forgedFile,JSON.stringify(core.issue(privateKey,{systemId:wrongId,clientName:'Other computer'})));
    await client.evaluate(({dialog},file)=>{dialog.showOpenDialog=async()=>({canceled:false,filePaths:[file]});},forgedFile);
    await locked.locator('#activate').click();await locked.waitForFunction('document.getElementById("status").textContent.includes("different computer")');
    assert.equal(await locked.evaluate('typeof KPAutomaticCalculations'),'undefined');
    await client.evaluate(({dialog},file)=>{dialog.showOpenDialog=async()=>({canceled:false,filePaths:[file]});},licenseFile);
    await locked.locator('#activate').click();await locked.waitForURL('**/app/index.html',{timeout:120000});
    await locked.waitForFunction('document.readyState==="complete" && typeof KPAutomaticCalculations!=="undefined"',null,{timeout:120000});
    assert.equal(await locked.evaluate('currentKPModel.ready'),true);
    const userData=await client.evaluate(({app})=>app.getPath('userData'));
    assert.equal(core.verify(await fs.readFile(path.join(userData,'system-license.json'),'utf8'),publicPem,systemId).clientName,'Runtime client');
    await client.close();client=null;
    console.log('PASS client: unlicensed workspace blocked; machine mismatch rejected; valid signed activation opens the offline engine.');
    client=await _electron.launch(options(root));const reopened=await client.firstWindow();
    await reopened.waitForURL('**/app/index.html',{timeout:120000});await reopened.waitForFunction('typeof KPAutomaticCalculations!=="undefined"',null,{timeout:120000});
    assert.equal(await reopened.evaluate('currentKPModel.ready'),true);
    await client.close();client=null;
    await fs.writeFile(path.join(userData,'system-license.json'),JSON.stringify({...license,signature:'A'.repeat(86)}));
    client=await _electron.launch(options(root));const changed=await client.firstWindow();await changed.waitForSelector('#system-id');
    await changed.waitForFunction('document.getElementById("status").textContent.includes("software owner")');
    assert.equal(await changed.evaluate('typeof KPAutomaticCalculations'),'undefined');
    console.log('PASS restart: valid license persists offline; modified saved license locks the workspace again.');
    console.log('Artifacts: '+temporary+' (test keys only; never include in a release).');
  }finally{if(owner)await owner.close();if(client)await client.close();}
})().catch(error=>{console.error(error.stack);process.exitCode=1;});
